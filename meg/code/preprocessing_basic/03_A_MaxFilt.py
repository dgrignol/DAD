#!/usr/bin/env python3
"""
03_A_MaxFilt.py

Purpose
Run a FLUX Afirstlook-style first-pass quality check on one local raw MEG FIF
file by:
1) loading raw data metadata,
2) printing quick inspection summaries,
3) preparing Maxwell inputs (cross-talk/calibration files),
4) detecting noisy/flat sensors with FLUX `find_bad_channels_maxwell`,
5) printing detected noisy/flat channel lists for run-time feedback,
6) generating raw QC plots with detected bad channels marked,
7) computing Welch PSD on MEG channels,
8) generating bad-vs-good channel comparison plots (including MAG/GRAD refs),
9) saving a static PSD figure and an HTML report.
10) persisting the block01 bad-channel list into every saved `*_raw_sss.fif`
    header (`raw.info['bads']`) for downstream propagation.

Usage example
python /Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/code/preprocessing_basic/03_A_MaxFilt.py

Inputs
- Subject-specific raw FIF path derived from `subj_str`.
- Required MEGIN cross-talk FIF and calibration DAT files under:
  /Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/data/fwmegmaxfilter
  (if either sidecar is absent, the script fails before Maxwell processing).

Outputs
- PSD PNG under derivatives/preprocessing/sub-XX/ses-XX/figures/.
- HTML report under derivatives/reports/sub-XX/ses-XX/.
- Maxwell-filtered FIF files under derivatives/preprocessing/sub-XX/ses-XX/sss/
  with block01 bad channels explicitly stored in metadata (`info['bads']`).
"""

# %%
# -------------------------------------------------------------------------
# Imports
# -------------------------------------------------------------------------
# Import os for creating output directories.
import os
# Import os.path as op for extracting parent directories from file paths.
import os.path as op
import html

# Import MNE for reading FIF data and computing PSD.
import mne

# Import matplotlib module to configure backend before pyplot import.
import matplotlib

# Import pyplot for plotting and figure save/close operations.
import matplotlib.pyplot as plt

# %%
# -------------------------------------------------------------------------
# Subject/session selector section: keep all naming variants derived from one ID.
# -------------------------------------------------------------------------
# Two-digit subject string used to derive folder, BIDS, and file-prefix variants.
subj_str = "01"
# Two-digit session string used to derive BIDS-like session labels.
ses_str = "01"
# Single output folder for all static figures generated by this step.
figure_output_dir = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/derivatives/"
    f"preprocessing/sub-{subj_str}/ses-{ses_str}/figures"
)
# Create the figure output folder once at startup.
os.makedirs(figure_output_dir, exist_ok=True)

# -------------------------------------------------------------------------
# Figure I/O helper section: centralize save + log behavior for all figures.
# -------------------------------------------------------------------------
def savefig_logged(fig, filename, **kwargs):
    """
    Save a matplotlib figure into the shared figure output folder and log path.

    Inputs
    - fig: matplotlib figure object to save.
    - filename: output filename relative to figure_output_dir.
    - kwargs: forwarded keyword arguments for fig.savefig.
    """
    out_path = op.join(figure_output_dir, filename)
    fig.savefig(out_path, **kwargs)
    print(f"Saved figure to: {out_path}")


def attach_block01_bads(raw_obj, bad_channels):
    """
    Store the block01 bad-channel list in one Raw object's metadata.

    Parameters
    ----------
    raw_obj : mne.io.BaseRaw
        Raw object that will be saved to disk.
    bad_channels : list of str
        Canonical block01 bad-channel list to propagate downstream.
    """
    raw_obj.info["bads"] = list(dict.fromkeys(str(ch) for ch in bad_channels))

# %%
# -------------------------------------------------------------------------
# MNE HTML report section: add first-look plot and save report.
# -------------------------------------------------------------------------
# Create report container for this preprocessing step.
report = mne.Report(title=f"sub-{subj_str} | 03_A MaxFilt")


def log_to_console_and_report(text, *, title, section, tags=("log", "qc")):
    """
    Print text to console and also store it as a text block in the report.
    """
    print(text)
    report.add_html(
        f"<pre>{html.escape(text)}</pre>",
        title=title,
        section=section,
        tags=tags,
    )


# %%
# -------------------------------------------------------------------------
# Data input section: FLUX BIDS loader adaptation to local FIF file path.
# -------------------------------------------------------------------------
# Define the local raw FIF path used for first-look inspection.
fif_path = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/data/"
    f"sub{subj_str}/SUB{subj_str}_block01_meg.fif"
)

# Print the selected input path for run traceability.
print(fif_path)
# Load raw FIF headers and on-demand data access (no preload).
raw1 = mne.io.read_raw_fif(fif_path, preload=False, verbose=False)

# Print compact Raw object summary (channels, samples, duration).
print(raw1)
# Print detailed Info dictionary summary (sfreq, channel types, hardware fields).
print(raw1.info)


# %%
# -------------------------------------------------------------------------
# FLUX ApplyingMaxFilter (cell 10) prerequisites: define Maxwell sidecar files.
# -------------------------------------------------------------------------
# Define local sidecar paths provided by the MEG facility (FLUX-equivalent Maxwell files).
crosstalk_file = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/data/fwmegmaxfilter/"
    "ct_sparse_triux2.fif"
)
calibration_file = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/data/fwmegmaxfilter/"
    "sss_cal_3182_250410.dat"
)

# Require facility sidecars so bad-channel detection and Maxwell filtering use
# the same cross-talk/calibration inputs on every run.
if not op.exists(crosstalk_file) or not op.exists(calibration_file):
    raise FileNotFoundError("cross-talk/calibration files required.")

# Print sidecar paths to keep preprocessing provenance explicit.
print(f"crosstalk_file = {crosstalk_file}")
print(f"calibration_file = {calibration_file}")

# -------------------------------------------------------------------------
# FLUX ApplyingMaxFilter (cell 10): automatically identify noisy/flat sensors.
# -------------------------------------------------------------------------
# Reset manually marked bad channels before running FLUX bad-channel detection.
raw1.info["bads"] = []
# Copy data before automatic detection to avoid accidental in-place edits.
raw1_copy = raw1.copy().load_data()

# Run FLUX-equivalent Maxwell bad-channel finder (no parameter changes).
auto_noisy_chs, auto_flat_chs, auto_scores = mne.preprocessing.find_bad_channels_maxwell(
    raw1_copy,
    cross_talk=crosstalk_file,
    calibration=calibration_file,
    return_scores=True,
    verbose=True,
)

log_to_console_and_report(
    f"noisy = {auto_noisy_chs}\nflat = {auto_flat_chs}",
    title="Detected bad channels",
    section="Bad channels detection",
)

bads = auto_noisy_chs + auto_flat_chs # Aggregate detected bad channels once for downstream plot/report consistency.
# Trust Maxwell detection and set bad channels once on the main raw object.
raw1.info["bads"].extend(bads) # Extend (instead of overwrite) so existing/manual bads are preserved if present.
raw1.info["bads"] = list(dict.fromkeys(raw1.info["bads"])) # De-duplicate while preserving order in case noisy/flat lists overlap.
print('bads =', raw1.info['bads'])

# %%
# -------------------------------------------------------------------------
# Interactive inspection section: visualize raw after Maxwell bad detection.
# -------------------------------------------------------------------------
# Render a non-blocking first-look figure for the HTML report.
fig_raw = raw1.plot(
    duration=10,
    proj=False,
    title="Raw first look (Maxwell bads marked)",
    scalings="auto",
    bad_color="crimson",
    show=True,
)
report.add_figure(
    fig=fig_raw,
    title="Raw first look (10 s window)",
    caption=f"Maxwell bad channels: {bads}",
    section="First look",
    tags=("raw", "qc"),
)
# Save first-look raw QC figure in the shared figure output folder.
savefig_logged(fig_raw, "03_A_MaxFilt_first_look_raw.png", dpi=150, bbox_inches="tight")
plt.close(fig_raw)

# %%
# -------------------------------------------------------------------------
# PSD section: preserve FLUX Welch settings for direct comparability.
# -------------------------------------------------------------------------
# Set Welch FFT window length to 2000 samples (2 seconds at 1000 Hz).
n_fft = 2000
# Compute PSD over MEG channels using FLUX-aligned parameters.
data1PSD = raw1.compute_psd(
    method="welch",  # Use Welch spectral estimation (same as FLUX first-look).
    fmin=1,  # Lower frequency bound in Hz.
    fmax=60,  # Upper frequency bound in Hz.
    picks="meg",  # Restrict PSD to MEG channels.
    n_fft=n_fft,  # FFT length in samples.
    n_overlap=int(n_fft / 2),  # 50% overlap between adjacent Welch windows.
)

# Create PSD figure object without opening an interactive window.
fig_psd = data1PSD.plot(show=True)
report.add_figure(
    fig=fig_psd,
    title="PSD figure",
    section="First look",
    tags=("ft", "qc"),
)

# Define destination path for saved first-look PSD image.
# Save figure to PNG with stable resolution and tight bounding box.
savefig_logged(fig_psd, "03_A_MaxFilt_first_look_psd.png", dpi=150, bbox_inches="tight")
# Close figure to release memory and avoid backend resource buildup.
plt.close(fig_psd)

# %%
# -------------------------------------------------------------------------
# FLUX-style bad-channel comparison: bad channels + one MAG + one GRAD.
# -------------------------------------------------------------------------
# Select reference good channels by Neuromag naming:
# - MAG channels end with "1"
# - GRAD channels end with "2" or "3"
good_meg = [ch for ch in raw1.ch_names if ch.startswith("MEG") and ch not in bads]
mag_ref = next((ch for ch in good_meg if ch.endswith("1")), None)
grad_ref = next((ch for ch in good_meg if ch.endswith(("2", "3"))), None)
ref_chs = [ch for ch in (mag_ref, grad_ref) if ch is not None]

# Build comparison picks with robust fallback if no bads were detected.
picks_cmp = bads + ref_chs
if not picks_cmp:
    picks_cmp = [ch for ch in raw1.ch_names if ch.startswith("MEG")][:2]

fig_noisy_chan_raw = raw1.copy().load_data().pick(picks_cmp).plot(
    proj=False,
    scalings="auto",  # Auto-adjust y scale across selected channels.
    clipping=None,  # Avoid hard clipping so artifact amplitudes remain visible.
    remove_dc=True,
    n_channels=len(picks_cmp),
    group_by="type",  # Built-in MAG/GRAD grouping in the browser.
    bad_color="crimson",  # Built-in coloring for channels in info['bads'].
    show_options=False,
    show=True,
)

report.add_figure(
    fig=fig_noisy_chan_raw,
    title="Noisy channels identified by Maxwell (with MAG/GRAD references)",
    caption=f"Reference magnetometer: {mag_ref}; reference gradiometer: {grad_ref}",
    section="Bad channels detection",
    tags=("raw", "qc"),
)
# Save bad-channel raw comparison figure in the shared figure output folder.
savefig_logged(
    fig_noisy_chan_raw,
    "03_A_MaxFilt_bad_channels_raw_comparison.png",
    dpi=150,
    bbox_inches="tight",
)
plt.close(fig_noisy_chan_raw)

n_fft = 2000
temp_psd = raw1_copy.copy().pick(picks_cmp).compute_psd(
    method="welch",
    fmin=1,
    fmax=60,
    n_fft=n_fft,
    n_overlap=int(n_fft / 2),
)
fig_noisy_chan_psd = temp_psd.plot(show=True, spatial_colors=False)

report.add_figure(
    fig=fig_noisy_chan_psd,
    title="Noisy channels PSD comparison (bad + MAG/GRAD references)",
    caption=f"Channels: {picks_cmp}",
    section="Bad channels detection",
    tags=("psd", "qc"),
)
# Save bad-channel PSD comparison figure in the shared figure output folder.
savefig_logged(
    fig_noisy_chan_psd,
    "03_A_MaxFilt_bad_channels_psd_comparison.png",
    dpi=150,
    bbox_inches="tight",
)
plt.close(fig_noisy_chan_psd)


# %%
# Change coil types to match Maxwell-filter expectations (FLUX-equivalent step).
raw1.fix_mag_coil_types()

# %%
# Apply Maxwell filter to the first file (FLUX run-01 equivalent).
raw1_sss = mne.preprocessing.maxwell_filter(
    raw1,
    cross_talk=crosstalk_file,
    calibration=calibration_file,
    verbose=True,
)
# Maxwell output can drop bad-channel markers; reattach block01 bads so
# downstream steps (03_B/03_C/04/06) can reliably read `info['bads']`.
attach_block01_bads(raw1_sss, bads)

# Compute and plot PSD on raw vs Maxwell-filtered data to confirm expected noise reduction.
fig_psd_raw_pre_sss = raw1.compute_psd(fmax=60, n_fft=1000).plot(show=True)
report.add_figure(
    fig=fig_psd_raw_pre_sss,
    title="Raw PSD before Maxwell filter",
    section="Maxwell filter",
    tags=("psd", "qc"),
)
savefig_logged(fig_psd_raw_pre_sss, "03_A_MaxFilt_psd_pre_maxwell.png", dpi=150, bbox_inches="tight")
plt.close(fig_psd_raw_pre_sss)

fig_psd_raw_post_sss = raw1_sss.compute_psd(fmax=60, n_fft=1000).plot(show=True)
report.add_figure(
    fig=fig_psd_raw_post_sss,
    title="Raw PSD after Maxwell filter",
    section="Maxwell filter",
    tags=("psd", "qc"),
)
savefig_logged(fig_psd_raw_post_sss, "03_A_MaxFilt_psd_post_maxwell.png", dpi=150, bbox_inches="tight")
plt.close(fig_psd_raw_post_sss)

# Save the Maxwell-filtered first file under derivatives/preprocessing/.../sss.
sss_output_dir = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/derivatives/"
    f"preprocessing/sub-{subj_str}/ses-{ses_str}/sss"
)
os.makedirs(sss_output_dir, exist_ok=True)
deriv_file_1 = op.join(sss_output_dir, f"SUB{subj_str}_block01_raw_sss.fif")
raw1_sss.save(deriv_file_1, overwrite=True)
print(f"Saved Maxwell-filtered first file to: {deriv_file_1}")

# FLUX tutorial style: reuse bads from the first file and apply to all remaining files.
data_subj_dir = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/data/"
    f"sub{subj_str}"
)
all_block_files = sorted(
    op.join(data_subj_dir, fname)
    for fname in os.listdir(data_subj_dir)
    if fname.startswith(f"SUB{subj_str}_block") and fname.endswith("_meg.fif")
)
print(f"Discovered block files for SSS: {all_block_files}")

# Keep a per-file record of automatically detected bad channels for end-of-loop reporting.
run_bad_detection_summary = [
    {
        "file": op.basename(fif_path),
        "detected_bads": list(dict.fromkeys(bads)),
        "note": "reference_block01_used_for_sss",
    }
]

processed_additional_count = 0
for fif_path_run in all_block_files:
    # Skip first file because it has already been processed above as raw1/raw1_sss.
    if op.abspath(fif_path_run) == op.abspath(fif_path):
        continue

    print(f"Processing additional file with reused bads from block01: {fif_path_run}")
    raw_run = mne.io.read_raw_fif(fif_path_run, preload=True, verbose=True)

    # Consistency check: detect run-specific bad channels, but keep FLUX tutorial
    # behavior by still applying block01 bads for Maxwell filtering.
    raw_run_check = raw_run.copy()
    raw_run_check.info["bads"] = []
    run_noisy_chs, run_flat_chs, _ = mne.preprocessing.find_bad_channels_maxwell(
        raw_run_check,
        cross_talk=crosstalk_file,
        calibration=calibration_file,
        return_scores=True,
        verbose=False,
    )
    run_bads = list(dict.fromkeys(run_noisy_chs + run_flat_chs))
    missing_vs_block01 = sorted(set(bads) - set(run_bads))
    extra_vs_block01 = sorted(set(run_bads) - set(bads))
    run_bad_detection_summary.append(
        {
            "file": op.basename(fif_path_run),
            "detected_bads": run_bads,
            "note": "mismatch" if (missing_vs_block01 or extra_vs_block01) else "match",
        }
    )
    if missing_vs_block01 or extra_vs_block01:
        print(
            "WARNING: bad-channel consistency mismatch for "
            f"{op.basename(fif_path_run)}. "
            f"Detected in this file: {run_bads}; "
            f"missing_vs_block01: {missing_vs_block01}; "
            f"extra_vs_block01: {extra_vs_block01}. "
            f"Proceeding with block01 bads for SSS: {bads}"
        )
    else:
        print(
            "Bad-channel consistency check OK for "
            f"{op.basename(fif_path_run)} (matches block01 bad list)."
        )

    raw_run.info["bads"].extend(bads)
    raw_run.info["bads"] = list(dict.fromkeys(raw_run.info["bads"]))
    raw_run.fix_mag_coil_types()
    raw_run_sss = mne.preprocessing.maxwell_filter(
        raw_run,
        cross_talk=crosstalk_file,
        calibration=calibration_file,
        verbose=True,
    )
    # Mirror block01 bad-channel metadata into each SSS output header.
    attach_block01_bads(raw_run_sss, bads)

    deriv_file_run = op.join(
        sss_output_dir, op.basename(fif_path_run).replace("_meg.fif", "_raw_sss.fif")
    )
    raw_run_sss.save(deriv_file_run, overwrite=True)
    print(f"Saved Maxwell-filtered file to: {deriv_file_run}")
    processed_additional_count += 1

if processed_additional_count == 0:
    print("No additional files found for SSS beyond block01.")

summary_lines = ["Bad-channel detection summary by file:"]
for item in run_bad_detection_summary:
    summary_lines.append(
        f"  {item['file']}: detected_bads={item['detected_bads']} (status={item['note']})"
    )
log_to_console_and_report(
    "\n".join(summary_lines)
    + "\n\n"
    + "Propagation policy:\n"
    + f"  block01_bad_channels_persisted_in_sss_headers={list(dict.fromkeys(bads))}",
    title="Bad-channel consistency summary",
    section="Maxwell filter",
)

# %%
# This stays at the end of the script to ensure all processing steps are completed before report generation and saving.
# Save HTML report.
out_report = (
    "/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/derivatives/"
    f"reports/sub-{subj_str}/ses-{ses_str}/03_A_MaxFilt_report.html"
)
os.makedirs(op.dirname(out_report), exist_ok=True)
report.save(out_report, overwrite=True, open_browser=False)
print(f"Saved HTML report to: {out_report}")
