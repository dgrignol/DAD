def run_epoching(
    cfg: Mapping[str, Any],
    *,
    source_manifest: str | Path,
    overwrite: bool,
    validate_only: bool = False,
    print_summary: bool = False,
    timing_review: str | Path | None = None,
    eligibility_application: str | Path | None = None,
) -> dict[str, Any]:
    """
    Validate lineage, create per-run epochs, concatenate, and write reports.

    Parameters
    ----------
    cfg
        Resolved pipeline configuration.
    source_manifest
        Durable manifest containing completed manual-ICA apply lineage.
    overwrite
        Whether existing scientific outputs may be replaced.
    validate_only
        Stop after validating cleaning, trigger, timing and output contracts.
    print_summary
        Print compact resolved settings and final counts.
    timing_review
        Accepted Stage 3 review record. Joins the immutable Stage 2 keys and
        adds reviewed event samples without changing their original anchors.
    eligibility_application
        Optional explicit application.json bound to the reviewed timing bundle.
        Its hashes, original policy and scientific review scopes are verified;
        final_analysis_eligible controls event selection while the original
        included_by_trial_policy and exclusion reasons remain in epoch metadata.

    Returns
    -------
    dict
        Machine-readable stage report.
    """
    raw_root = cfg["resolved_paths"]["data_root"]
    epoch_cfg = cfg["epoching"]
    timing_review = timing_review or epoch_cfg.get("timing_review_path")
    paths = epoching_paths(cfg)
    base = upstream_config(cfg)
    output_manifest = processing_manifest(cfg, source_manifest)
    canonical_manifest = Path(base["resolved_paths"]["derivatives_reports_dir"]) / "source_manifest.json"
    cleaned_runs, stage03_gate, model = resolve_epoch_inputs(cfg,
        canonical_manifest if cfg["epoching"].get("processing_run") else source_manifest)
    event_rows = load_trigger_event_rows(paths["events_csv"])
    grouped_events = rows_by_source_fif(event_rows)
    prepared = (load_prepared_decisions(base)
                if epoch_cfg.get("require_stage2_ledger", False) else None)
    if prepared is not None:
        if {row["source_fif"] for row in prepared} != set(grouped_events):
            raise RuntimeError("Stage 2 ledger and epoching source sets disagree.")

    # Join the reviewed timing overlay only after verifying original accounting.
    # The added sample field is used for events; original keys remain untouched.
    timing_gate = None
    if timing_review:
        if prepared is None:
            raise RuntimeError("Stage 3 timing requires the verified Stage 2 ledger.")
        prepared, timing_gate = load_reviewed_timing(base, prepared, timing_review,eligibility_application)
    elif epoch_cfg.get("require_stage3_timing", False) and 4 <= int(cfg["subject"]["id"]) <= 39:
        raise RuntimeError("Current-cohort epoching requires --timing-review with accepted Stage 3 timing.")
    elif eligibility_application:
        raise RuntimeError("An eligibility application requires the accepted Stage 3 timing review.")
    if epoch_cfg.get("annotation_end_trims"):
        from epoch_annotation_trims import validate_trial_bindings
        validate_trial_bindings(cfg, prepared)

    for output_key in (
        "epochs_fif",
        "epoch_metadata_csv",
        "trial_decisions_csv",
        "report_json",
        "report_html",
    ):
        guarded_path(paths[output_key], raw_root)

    setup = {
        "stage": "epoching",
        "status": "validated" if validate_only else "running",
        "generated_utc": utc_now(),
        "subject_bids_id": cfg["layout"]["subject_bids_id"],
        "session_bids_id": cfg["layout"]["session_bids_id"],
        "event_id_map": dict(epoch_cfg["event_id_map"]),
        "identity_range": list(cfg["subject_profile"]["identity_range"]),
        "epoch_window_sec": [
            float(epoch_cfg["tmin_sec"]),
            float(epoch_cfg["tmax_sec"]),
        ],
        "baseline_sec": epoch_cfg["baseline_sec"],
        "baseline_correction_applied": epoch_cfg["baseline_sec"] is not None,
        "detrend": epoch_cfg["detrend"],
        "reject_by_annotation": bool(epoch_cfg["reject_by_annotation"]),
        "filter_edge_policy": "informational_only_keep_eligible_epochs",
        "amplitude_rejection_enabled": bool(epoch_cfg.get("amplitude_rejection_enabled", True)),
        "amplitude_reject": (dict(epoch_cfg["amplitude_reject"])
            if epoch_cfg.get("amplitude_rejection_enabled", True) else {}),
        "trial_exclusion_policy": dict(epoch_cfg["trial_exclusion"]),
        "stage2_trial_ledger": str(stage2_paths(base)["ledger"]) if prepared is not None else None,
        "stage03_gate": stage03_gate,
        "stage3_timing_gate": timing_gate,
        "preparation_contract": epoch_contract(cfg, stage03_gate, timing_gate, events_csv=paths["events_csv"]),
        "inputs": {
            "events_csv": str(paths["events_csv"]),
            "source_manifest": str(output_manifest),
            ("cleaned_fifs" if epoch_cfg.get("preparation_mode", "saved_ica") == "saved_ica"
             else "continuous_fifs"): [item.cleaned_path for item in cleaned_runs],
        },
        "outputs": {key: str(value) for key, value in paths.items() if key != "events_csv"},
        "iti_compatibility": {
            "verified_subject_iti_sec_range": list(
                cfg["subject_profile"]["iti_sec_range"]
            ),
            "epoch_tmin_sec": float(epoch_cfg["tmin_sec"]),
            "dot_side_baseline_sec": [-0.4, -0.2],
            "erf_baseline_sec": [-0.1, 0.0],
            "status": "compatible",
            "reason": (
                "Both downstream baseline windows are within the configured "
                "-0.5 s pre-stimulus epoch. Epoching itself applies no baseline."
            ),
        },
    }
    if print_summary:
        print(json.dumps(setup, indent=2, sort_keys=True))
    if validate_only:
        return setup

    # A label is an immutable scientific variant. Changed settings or partial
    # outputs require a new label; --overwrite cannot mix two variants.
    if epoch_cfg.get("processing_run") and (any(paths[key].exists() for key in
            ("epochs_fif", "epoch_metadata_csv", "trial_decisions_csv", "report_json"))
            or any((paths["report_json"].parent / "epoch_input_qc").glob("*.png"))):
        raise RuntimeError("Processing-run epoch outputs already exist; resume a matching completed run or choose a new label.")
    output_manifest = processing_manifest(cfg, source_manifest, create=True)
    ensure_output_directory(paths["epochs_fif"].parent, raw_root)
    ensure_output_directory(paths["report_json"].parent, raw_root)
    for output_key in (
        "epochs_fif",
        "epoch_metadata_csv",
        "trial_decisions_csv",
        "report_json",
        "report_html",
    ):
        prepare_output_path(
            paths[output_key],
            raw_root=raw_root,
            overwrite=overwrite,
        )

    event_id = {str(name): int(code) for name, code in epoch_cfg["event_id_map"].items()}
    identity_min, identity_max = cfg["subject_profile"]["identity_range"]
    identity_range = range(int(identity_min), int(identity_max) + 1)
    baseline = _baseline_value(epoch_cfg["baseline_sec"])
    # Keep configured threshold values for provenance. The explicit switch
    # controls MNE's reject argument; an empty YAML mapping would otherwise
    # inherit default thresholds through the recursive configuration merge.
    amplitude_reject = ({
        str(key): float(value)
        for key, value in epoch_cfg["amplitude_reject"].items()
    } or None) if epoch_cfg.get("amplitude_rejection_enabled", True) else None

    epochs_by_run: list[mne.Epochs] = []
    all_decisions: list[dict[str, Any]] = []
    lineage_records: list[dict[str, Any]] = []
    per_run_reports: list[dict[str, Any]] = []
    for cleaned_run in cleaned_runs:
        raw, preparation_qc = prepare_run(cfg, cleaned_run, stage03_gate["preparation"], model,
            paths["report_json"].parent / "epoch_input_qc")
        # The 2026-10-23 decision keeps edge-exposed epochs. Normalize only the
        # legacy edge category; keep artifact rejection and native boundaries.
        make_filter_edges_informational(raw)
        source_fif = cleaned_run.source.source_filename
        decisions = ([dict(row) for row in prepared if row["source_fif"] == source_fif]
                     if prepared is not None else build_trial_decisions(
            grouped_events.get(source_fif, []),
            source_fif=source_fif,
            run_end_sample_exclusive=int(raw.first_samp + raw.n_times),
            event_id_map=event_id,
            identity_range=identity_range,
            exclusion_policy=epoch_cfg["trial_exclusion"],
            accepted_exclusions=epoch_cfg.get("accepted_trial_exclusions", []),
        ))
        if prepared is not None and any(
            int(row["recording_first_sample_raw"]) != int(raw.first_samp)
            or int(row["recording_end_sample_raw_exclusive"]) != int(raw.first_samp + raw.n_times)
            or float(row["sfreq_hz"]) != float(raw.info["sfreq"])
            for row in decisions
        ):
            raise RuntimeError(f"Cleaned-run coordinates differ from Stage 2: {source_fif}")
        candidates = [
            decision
            for decision in decisions
            if analysis_eligible(decision)
        ]
        if not candidates:
            raise RuntimeError(
                f"Trial policy removed every condition event from {source_fif}."
            )
        events = np.asarray(
            [
                [
                    int(decision.get("epoch_event_sample_raw", decision["raw_sample_frame"])),
                    0,
                    int(decision["condition_code"]),
                ]
                for decision in candidates
            ],
            dtype=int,
        )
        metadata = pd.DataFrame(candidates)
        epochs_run = mne.Epochs(
            raw,
            events,
            event_id=event_id,
            tmin=float(epoch_cfg["tmin_sec"]),
            tmax=float(epoch_cfg["tmax_sec"]),
            baseline=baseline,
            proj=False,
            picks="all",
            detrend=int(epoch_cfg["detrend"]),
            reject=amplitude_reject,
            reject_by_annotation=bool(epoch_cfg["reject_by_annotation"]),
            metadata=metadata,
            preload=True,
            on_missing="ignore",
            verbose=False,
        )
        _mark_mne_outcomes(decisions, candidates, epochs_run)
        if len(epochs_run) == 0:
            raise RuntimeError(
                f"MNE rejection removed every candidate epoch from {source_fif}."
            )
        epochs_by_run.append(epochs_run)
        all_decisions.extend(decisions)
        per_run_reports.append(
            {
                "source_fif": source_fif,
                "acquisition_run": cleaned_run.source.acquisition_run_label,
                "cleaned_path": cleaned_run.cleaned_path,
                "continuous_preparation_qc": preparation_qc,
                "n_condition_trials": len(decisions),
                "n_trial_policy_candidates": len(candidates),
                "n_final_analysis_candidates": len(candidates),
                "n_original_stage2_eligible": sum(bool(row["included_by_trial_policy"]) for row in decisions),
                "n_surviving_epochs": len(epochs_run),
                "trial_policy_exclusion_counts": _count_values(
                    [
                        decision
                        for decision in decisions
                        if not analysis_eligible(decision)
                    ],
                    "analysis_exclusion_reasons" if timing_gate and timing_gate.get("eligibility_application") else "exclusion_reasons",
                ),
                "mne_drop_counts": dict(
                    sorted(
                        Counter(
                            reason
                            for entry in epochs_run.drop_log
                            for reason in entry
                        ).items()
                    )
                ),
            }
        )
        lineage_records.append(
            lineage_record(
                source=cleaned_run.source,
                input_path=cleaned_run.cleaned_path,
                output_path=paths["epochs_fif"],
                status="completed",
                metadata={
                    "n_condition_trials": len(decisions),
                    "n_surviving_epochs": len(epochs_run),
                    "manual_ica_manifest_output": cleaned_run.manifest_output_path or None,
                    "preparation_mode": epoch_cfg.get("preparation_mode", "saved_ica"),
                    "preparation_contract_sha256": setup["preparation_contract"]["sha256"],
                },
            )
        )
        # Epochs own their loaded samples. Release this recording before the
        # next acquisition to keep participant memory bounded.
        raw.close()
        del raw

    epochs = mne.concatenate_epochs(
        epochs_by_run,
        add_offset=True,
        on_mismatch="warn",
        verbose=False,
    )
    if epochs.metadata is None:
        raise RuntimeError("Concatenated epochs unexpectedly lost metadata.")
    epochs.metadata = epochs.metadata.copy()
    epochs.metadata["concat_epoch_sample"] = epochs.events[:, 0].astype(int)
    epochs.info["description"] = (
        f"DAD condition epochs; {epoch_cfg.get('preparation_mode', 'saved_ica')} inputs; baseline=None by default; "
        "trial exclusions documented in 04_epoching_report.json."
    )

    epochs.save(paths["epochs_fif"], overwrite=True, verbose=False)
    epochs.metadata.to_csv(paths["epoch_metadata_csv"], index=False)
    pd.DataFrame(all_decisions).to_csv(paths["trial_decisions_csv"], index=False)

    final_metadata = epochs.metadata.to_dict(orient="records")
    report = {
        **setup,
        "status": "completed",
        "finished_utc": utc_now(),
        "artifact_bindings": artifact_binding(paths),
        "per_run": per_run_reports,
        "counts": {
            "n_trial_decisions": len(all_decisions),
            "n_trial_policy_candidates": sum(
                analysis_eligible(row) for row in all_decisions
            ),
            "n_original_stage2_eligible": sum(bool(row["included_by_trial_policy"]) for row in all_decisions),
            "n_final_analysis_candidates": sum(analysis_eligible(row) for row in all_decisions),
            "n_final_epochs": len(epochs),
            "final_by_condition": _count_values(final_metadata, "condition_name"),
            "final_by_identity": _count_values(
                final_metadata,
                "trial_sequence_identity",
            ),
            "trial_policy_exclusions": _count_values(
                [
                    row
                    for row in all_decisions
                    if not analysis_eligible(row)
                ],
                "analysis_exclusion_reasons" if timing_gate and timing_gate.get("eligibility_application") else "exclusion_reasons",
            ),
            "mne_drop_reasons": dict(
                sorted(
                    Counter(
                        reason
                        for row in all_decisions
                        for reason in str(row.get("mne_drop_reasons", "")).split(",")
                        if reason
                    ).items()
                )
            ),
            "replay_trials_final": sum(
                bool(row["is_replay_trial"]) for row in final_metadata
            ),
        },
        "metadata_columns": list(epochs.metadata.columns),
        "channel_summary": {
            "n_channels": len(epochs.ch_names),
            "marked_bad_channels": list(epochs.info.get("bads", [])),
        },
        "annotation_policy": {
            "trial_trigger_exclusions": (
                "Applied before MNE epoch construction using run-isolated "
                "canonical trigger intervals."
            ),
            "physiological_annotations": (
                "Handled independently by MNE reject_by_annotation; trigger-150 "
                "is not treated as a physiological annotation."
            ),
        },
    }
    write_json(paths["report_json"], report, raw_root=raw_root, overwrite=True)
    write_simple_html_report(
        paths["report_html"],
        title=f"{cfg['layout']['subject_bids_id']} | 04 Epoching",
        summary_lines=[
            "Stage status: completed",
            f"Final epochs: {len(epochs)}",
            f"By condition: {report['counts']['final_by_condition']}",
            f"Trial-policy exclusions: {report['counts']['trial_policy_exclusions']}",
            f"MNE drop reasons: {report['counts']['mne_drop_reasons']}",
            f"Epoch window: {report['epoch_window_sec']} s",
            "Baseline correction applied: "
            f"{report['baseline_correction_applied']}",
            f"Epochs FIF: {paths['epochs_fif']}",
            f"Machine report: {paths['report_json']}",
        ],
        image_paths=[Path(value) for row in per_run_reports for key, value in
            (row.get("continuous_preparation_qc") or {}).items()
            if key in ("line_removal_figure", "ica_only_figure", "p10_slow_qc") and value],
        raw_root=raw_root,
    )
    manifest_status = update_source_manifest_stage(
        manifest_path=output_manifest,
        raw_root=raw_root,
        stage_name="epoching",
        processing_pass="apply",
        records=lineage_records,
        status="completed",
        qc={
            "report_json": str(paths["report_json"]),
            "report_html": str(paths["report_html"]),
            "epochs_fif": str(paths["epochs_fif"]),
            "n_final_epochs": len(epochs),
            "event_id_map": event_id,
            "baseline_sec": epoch_cfg["baseline_sec"],
            "detrend": epoch_cfg["detrend"],
            "stage3_timing_gate": timing_gate,
            "preparation_contract_sha256": setup["preparation_contract"]["sha256"],
        },
    )
    report["source_manifest_update"] = manifest_status
    write_json(paths["report_json"], report, raw_root=raw_root, overwrite=True)
    if print_summary:
        print(json.dumps(report["counts"], indent=2, sort_keys=True))
    return report


def main() -> int:
    """Resolve configuration and execute the epoching stage."""
    args = build_arg_parser().parse_args()
    if args.resume and args.overwrite:
        raise SystemExit("--resume and --overwrite are mutually exclusive.")
    cfg, warnings, _config_path, _subject_path = load_and_resolve_config(
        args.config,
        args.subject_config,
        args.tuning_config,
        site_config_path=args.site_config,
        required_sections=("epoching",),
    )
    if warnings and args.print_summary:
        print(json.dumps({"configuration_warnings": warnings}, indent=2))
    paths = epoching_paths(cfg)
    if args.resume and paths["epochs_fif"].is_file() and paths["report_json"].is_file():
        if cfg["epoching"].get("processing_run"):
            current = run_epoching(cfg, source_manifest=args.source_manifest, overwrite=False,
                validate_only=True, timing_review=args.timing_review,
                eligibility_application=args.eligibility_application)
            previous = verify_epoch_artifacts(cfg)
            if current["preparation_contract"] != previous["preparation_contract"]:
                raise RuntimeError("Epoch input/model/timing contract changed; use a new processing-run label.")
            print(f"Resumed verified epoching outputs: {paths['epochs_fif']}")
            return 0
        # Outputs made under the former edge-rejection rule cannot silently
        # satisfy the accepted retention policy, even when inputs are unchanged.
        previous_report = json.loads(paths["report_json"].read_text())
        if previous_report.get("filter_edge_policy") != "informational_only_keep_eligible_epochs":
            raise RuntimeError("Existing epochs lack the accepted informational filter-edge policy; rebuild epoch evidence.")
        # An old digital-only epoch file cannot satisfy a new reviewed-timing
        # request merely because its pathname exists.
        review_path = args.timing_review or cfg["epoching"].get("timing_review_path")
        needs_timing = cfg["epoching"].get("require_stage3_timing", False) and 4 <= int(cfg["subject"]["id"]) <= 39
        if needs_timing or review_path or args.eligibility_application:
            if not review_path:
                raise RuntimeError("Resume requires the accepted Stage 3 timing review.")
            _, gate = load_reviewed_timing(cfg, load_prepared_decisions(cfg), review_path,args.eligibility_application)
            previous = previous_report.get("stage3_timing_gate")
            if previous != gate:
                raise RuntimeError("Existing epochs have different or absent reviewed Stage 3 timing.")
        print(f"Resumed existing epoching outputs: {paths['epochs_fif']}")
        return 0
    run_epoching(
        cfg,
        source_manifest=args.source_manifest,
        overwrite=bool(args.overwrite or cfg["runtime"]["overwrite_existing"]),
        validate_only=args.validate_only,
        print_summary=args.print_summary,
        timing_review=args.timing_review,
        eligibility_application=args.eligibility_application,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
