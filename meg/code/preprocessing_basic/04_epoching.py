def build_arg_parser() -> argparse.ArgumentParser:
    """Create the noninteractive epoching command-line parser."""
    parser = argparse.ArgumentParser(
        description="Create lineage-matched multisubject DAD MEG epochs."
    )
    parser.add_argument("--config", required=True)
    parser.add_argument("--site-config", default=None)
    parser.add_argument("--subject-config", default=None)
    parser.add_argument("--tuning-config", default=None)
    parser.add_argument("--source-manifest", required=True)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--validate-only", action="store_true")
    parser.add_argument("--print-summary", action="store_true")
    parser.add_argument("--timing-review", default=None,
                        help="Explicit accepted Stage 3 review JSON; required for P04-P39 production.")
    parser.add_argument("--eligibility-application",default=None,
                        help="Optional explicit application.json bound to the accepted timing bundle; never bypasses review.")
    return parser


def epoching_paths(cfg: Mapping[str, Any]) -> dict[str, Path]:
    """Return canonical guarded inputs and outputs for one subject."""
    resolved = cfg["resolved_paths"]
    subject = cfg["layout"]["subject_bids_id"]
    session = cfg["layout"]["session_bids_id"]
    preprocessing = Path(resolved["derivatives_preprocessing_dir"])
    analysis_meg = Path(resolved["derivatives_analysis_dir"]) / "meg"
    reports = Path(resolved["derivatives_reports_dir"])
    stem = f"{subject}_{session}_task-Attention_run-all"
    return {
        "events_csv": preprocessing / "events" / "02_trigger_events.csv",
        "epochs_fif": analysis_meg / f"{stem}_epo.fif",
        "epoch_metadata_csv": analysis_meg / f"{stem}_epoch_metadata.csv",
        "trial_decisions_csv": analysis_meg / f"{stem}_trial_decisions.csv",
        "report_json": reports / "04_epoching_report.json",
        "report_html": reports / "04_epoching_report.html",
    }


def _baseline_value(value: Any) -> tuple[float | None, float | None] | None:
    """Convert YAML baseline settings to the MNE baseline argument."""
    if value is None:
        return None
    if not isinstance(value, list) or len(value) != 2:
        raise ValueError("`epoching.baseline_sec` must be null or a two-item list.")
    return tuple(None if item is None else float(item) for item in value)


def _count_values(rows: list[Mapping[str, Any]], key: str) -> dict[str, int]:
    """Count populated metadata values with stable string keys for JSON."""
    return dict(
        sorted(Counter(str(row[key]) for row in rows).items())
    )


def _mark_mne_outcomes(
    decisions: list[dict[str, Any]],
    candidate_decisions: list[dict[str, Any]],
    epochs: mne.Epochs,
) -> None:
    """
    Attach MNE drop reasons and final inclusion state to trial decisions.

    ``epochs.selection`` indexes the candidate event array supplied to MNE.
    This preserves the distinction between explicit trial-policy exclusions and
    annotation/amplitude/window drops performed during epoch construction.
    """
    surviving_indices = set(int(value) for value in epochs.selection)
    for candidate_index, decision in enumerate(candidate_decisions):
        drop_reasons = list(epochs.drop_log[candidate_index])
        decision["mne_drop_reasons"] = ",".join(drop_reasons)
        decision["included_final"] = candidate_index in surviving_indices
        decision["final_epoch_inclusion"] = (
            "included" if decision["included_final"] else "dropped_by_mne"
        )
    for decision in decisions:
        if not analysis_eligible(decision):
            decision["mne_drop_reasons"] = ""
            decision["included_final"] = False
            decision["final_epoch_inclusion"] = "excluded_before_epoching"


