#!/usr/bin/env python3
"""
04_epoching.py

Purpose
Create condition-locked DAD MEG epochs for one configured subject from the
lineage-matched manual-ICA apply outputs and canonical step-02 trigger events.
The stage preserves acquisition-run identity until each run has been epoched,
then concatenates the surviving epochs into one global epoch sample frame.

Usage examples
1) Epoch historical subject 01 after accepted cleaning (script 03_C apply):

   python /Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/code/preprocessing_basic/04_epoching.py \
     --config /Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/params/pipeline_default.yaml \
     --subject-config /Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/params/sub-01.yaml \
     --source-manifest /Volumes/MORWUR/Projects/DAMIANO/Attention/derivatives/reports/sub-01/ses-01/source_manifest.json

2) Validate inputs and print resolved outputs without reading full data:

   python .../04_epoching.py --config .../pipeline_default.yaml \
     --subject-config .../sub-04.yaml --source-manifest .../source_manifest.json \
     --validate-only --print-summary

3) Resume an already completed stage:

   python .../04_epoching.py --config ... --subject-config ... \
     --source-manifest ... --resume

Inputs
Inline modes (DAD_EPOCH_PREPARATION=inline_no_ica or inline_ica, together with
DAD_PROCESSING_RUN=NEW-LABEL) consume accepted native annotated FIFs directly.
Each continuous acquisition receives optional source-bound ICA followed by the
existing spectrum-fit line removal before epoch extraction, in memory. Only
epochs, small QC and a derived run manifest are saved. Canonical upstream data
and manifests remain read-only. Default saved_ica mode preserves the legacy CLI.

- ``source_manifest.json`` with a completed manual-ICA apply lineage record.
- One ``<exact-source-stem>_ica.fif`` per raw acquisition run.
- Canonical ``02_trigger_events.csv`` generated by trigger extraction.

Outputs
- Concatenated epochs FIF under the configured analysis directory.
- Surviving epoch metadata CSV with the global concatenated sample frame.
- Complete trial-decision CSV, including excluded and MNE-dropped trials.
- JSON and HTML reports documenting lineage, exclusion counts, epoch settings,
  ITI compatibility, annotation rejection, and output paths.
- An ``epoching`` derivative-lineage section in ``source_manifest.json``.

Scientific policy
- The configured default window is -0.5 to 2.667 s. This intentionally resolves
  the legacy hardcoded -1.0 s start and contains the downstream -0.4:-0.2 s and
  -0.1:0 s baseline windows for all verified subject ITIs.
- ``baseline=None`` means this stage performs no baseline correction.
- Linear detrending is retained with ``detrend=1``.
- ``amplitude_rejection_enabled=false`` disables only amplitude rejection in
  this stage; annotation and accepted trial/timing exclusions remain active.
  Explicit source-bound annotation end trims act on disposable inputs before
  line removal and do not rewrite accepted source/mask files.
- Trigger-150, both catch types, ESC termination, and unresolved transition
  evidence are trial-level policies configured separately from physiological
  ``BAD_*`` annotations handled by ``reject_by_annotation``.
- Final-filter edge exposure is informational: overlapping eligible epochs
  remain included. Only the exact legacy BAD_filter_edge label is normalized
  in memory; incomplete epochs and separately reviewed BAD artifacts keep
  their usual rejection rules.
- Replay trials are actual presented/saved trials and are included by default,
  with replay status retained in metadata.
- Production requires the completed Stage-2 trial ledger, checks its policy,
  evidence and output hashes, and preserves every accepted source/sample
  exclusion. A missing, changed, or review-required ledger stops epoching.
- Current-cohort production also requires ``--timing-review`` referencing a
  hash-bound accepted Stage 3 bundle. Original ``raw_sample_frame`` stays the
  trial identity; ``epoch_event_sample_raw`` supplies the reviewed epoch event.
  Proposal/pilot timing cannot feed epochs. Example after cleaning acceptance:
  ``python .../04_epoching.py ... --timing-review /derivatives/review/P11.json``.
  A reviewed application may separately revise analysis eligibility. Original
  Stage 2 flags/reasons remain intact; final_analysis_eligible selects events.
  Staging bundles and unaccepted application hashes/scopes remain blocked.
"""

