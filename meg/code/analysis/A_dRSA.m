% A_dRSA.m
%
% Purpose:
%   Run real-neural dRSA for one DAD MEG participant from Stage-06
%   identity-averaged neural exports and subject-specific trajectory models.
%   This script is the MATLAB computation layer behind the optional
%   matlab_drsa pipeline stage.
%
% Usage examples:
%   % Recommended: let Python generate the handoff and invoke this script.
%   %   python meg/code/preprocessing_basic/07_run_matlab_drsa.py \
%   %     --config meg/params/pipeline_default.yaml \
%   %     --subject-config meg/params/sub-04.yaml \
%   %     --source-manifest /Volumes/MORWUR/Projects/DAMIANO/Attention/derivatives/reports/sub-04/ses-01/source_manifest.json \
%   %     --analyses real --resume --print-summary
%
%   % Direct MATLAB run after a handoff exists:
%   drsa_handoff_json = '/Volumes/MORWUR/Projects/DAMIANO/Attention/derivatives/reports/sub-04/ses-01/07_matlab_drsa_handoff.json';
%   dRSAtypeToRun = 'corr'; % valid: corr or PCR
%   run('/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/code/analysis/A_dRSA.m');
%
% Inputs:
%   - drsa_handoff_json generated by 07_run_matlab_drsa.py.
%   - Stage-06 condition MAT files containing neural [identity x channel x time].
%   - Stage-06 JSON sidecars containing identity/time/channel metadata.
%   - Subject-specific observed trajectory MAT containing all conditions.
%   - dRSA helper functions under simulations/functions.
%
% Outputs:
%   <drsa_dir>/matlab_real_neural/07_dRSA/<condition>/<drsa_type>/
%     matrices/dRSA_<condition>_<drsa_type>_matrices.png
%     matrices/dRSA_<condition>_<drsa_type>_matrices_smoothed.png  (optional)
%     results/dRSA_<condition>_<drsa_type>_results.mat
%   Occluded-condition matrix PNGs include dashed horizontal lines marking
%   first complete occlusion and first reappearance from the handoff timing.
%   Panel titles and y-axes state the represented stimulus model, including
%   actual deviant, expected/predicted, and prediction-error occluded-deviant
%   models.
%
% Data flow:
%   handoff JSON -> Stage-06 neural tensors -> common non-NaN channel mask ->
%   sorted observed/expected trajectory tensors -> dRSA matrices -> PNG/MAT.
%
% Scientific assumptions:
%   - Identity values in Stage-06 exports match the trajectory sequence values.
%   - All three condition exports share time, channel, and identity axes.
%   - Bad/missing channels exported as all-NaN are removed before dRSA.
%   - Sub04-07 retain all 40 identities; no silent truncation to 20 occurs.

%% Reset workspace while preserving explicit runtime overrides
clearvars -except drsa_handoff_json dRSAtypeToRun plotSampleRateHz pcrStrategy doSmoothingPlots plotSmoothingWindow output_root_override

%% Runtime defaults and validated handoff
if ~exist('drsa_handoff_json', 'var') || isempty(drsa_handoff_json)
    error('Set drsa_handoff_json before running A_dRSA.m.');
end
if ~exist('dRSAtypeToRun', 'var') || isempty(dRSAtypeToRun)
    dRSAtypeToRun = 'corr';
end
if ~exist('pcrStrategy', 'var') || isempty(pcrStrategy)
    pcrStrategy = 'baseline_pcr_border';
end
if ~exist('doSmoothingPlots', 'var') || isempty(doSmoothingPlots)
    doSmoothingPlots = false;
end
if ~exist('plotSmoothingWindow', 'var') || isempty(plotSmoothingWindow)
    plotSmoothingWindow = 9;
end

handoff = drsa_stage_utils.load_handoff(drsa_handoff_json);
drsa_stage_utils.add_helper_paths(handoff);

if ~exist('plotSampleRateHz', 'var') || isempty(plotSampleRateHz)
    plotSampleRateHz = double(handoff.sampling_rate_hz);
end
if exist('output_root_override', 'var') && ~isempty(output_root_override)
    base_out_dir = char(output_root_override);
else
    base_out_dir = handoff.drsa_dir;
end

condition_struct = handoff.condition_outputs;
conditions = cellstr(string({condition_struct.name}));
identity_values = drsa_stage_utils.vectorize_numeric(handoff.identity_values);
time_axis_sec = drsa_stage_utils.vectorize_numeric(handoff.time_axis_sec);

fprintf('Running A_dRSA for %s %s: %d conditions, %d identities, %d timepoints.\n', ...
    handoff.subject_bids_id, handoff.session_bids_id, ...
    numel(conditions), numel(identity_values), numel(time_axis_sec));

%% Load neural tensors and enforce shared axes before channel cleanup
raw_input = struct();
ref_labels = [];
ref_time_count = numel(time_axis_sec);
nan_mask_by_condition = false(numel(conditions), 0);
for i_cond = 1:numel(conditions)
    cond = conditions{i_cond};
    [neural, channel_labels, sidecar] = drsa_stage_utils.load_neural_condition(handoff, cond);
    if size(neural, 1) ~= numel(identity_values)
        error('Identity count mismatch for %s.', cond);
    end
    if size(neural, 3) ~= ref_time_count
        error('Time count mismatch for %s.', cond);
    end
    if isempty(ref_labels)
        ref_labels = channel_labels(:);
        nan_mask_by_condition = false(numel(conditions), numel(ref_labels));
    elseif numel(channel_labels) ~= numel(ref_labels) || ~isequal(channel_labels(:), ref_labels(:))
        error('Channel-label order mismatch for %s.', cond);
    end

    field = matlab.lang.makeValidName(cond);
    raw_input.(field).neural = neural;
    raw_input.(field).sidecar = sidecar;
    nan_mask_by_condition(i_cond, :) = squeeze(all(all(isnan(neural), 3), 1));
end

remove_nan_mask = any(nan_mask_by_condition, 1);
kept_channel_labels = ref_labels(~remove_nan_mask);
removed_channel_labels = cellstr(ref_labels(remove_nan_mask));
if isempty(kept_channel_labels)
    error('All channels are all-NaN across at least one condition.');
end
fprintf('All-NaN channels removed before real-neural dRSA: %d\n', numel(removed_channel_labels));
fprintf('Channels retained: %d\n', numel(kept_channel_labels));

drsa_input = struct();
for i_cond = 1:numel(conditions)
    cond = conditions{i_cond};
    field = matlab.lang.makeValidName(cond);
    drsa_input.(field).neural = raw_input.(field).neural(:, ~remove_nan_mask, :);
    drsa_input.(field).channel_labels = kept_channel_labels(:);
end

%% Load trajectory models and build condition-specific model tensors
Obs = drsa_stage_utils.load_models(handoff);
model_input = struct();
n_time = numel(time_axis_sec);
for i_cond = 1:numel(conditions)
    cond = conditions{i_cond};
    field = matlab.lang.makeValidName(cond);
    [trials, model_source_used, center_shift, source_condition] = ...
        drsa_stage_utils.model_trials_for_condition(cond, 'observed', Obs);
    sorted_trials = drsa_stage_utils.sort_and_validate_sequences(trials, identity_values);
    [position_tensor, direction_tensor] = drsa_stage_utils.build_position_direction( ...
        sorted_trials, identity_values, n_time, center_shift);
    model_input.(field).observed_position = position_tensor;
    model_input.(field).observed_direction = direction_tensor;
    model_input.(field).observed_source = model_source_used;
    model_input.(field).observed_source_condition = source_condition;
end

% Expected and prediction-error models use the matched nondeviant continuation.
[pred_trials, pred_source, pred_center_shift, pred_source_condition] = ...
    drsa_stage_utils.model_trials_for_condition('occluded_deviant', 'predicted', Obs);
pred_sorted = drsa_stage_utils.sort_and_validate_sequences(pred_trials, identity_values);
[pred_position, pred_direction] = drsa_stage_utils.build_position_direction( ...
    pred_sorted, identity_values, n_time, pred_center_shift);
model_input.occluded_deviant.predicted_position = pred_position;
model_input.occluded_deviant.predicted_direction = pred_direction;
model_input.occluded_deviant.predicted_source = pred_source;
model_input.occluded_deviant.predicted_source_condition = pred_source_condition;

%% Run real-neural dRSA condition-by-condition
output_root = fullfile(base_out_dir, 'matlab_real_neural', '07_dRSA');
drsa_output = struct();

for i_cond = 1:numel(conditions)
    cond = conditions{i_cond};
    field = matlab.lang.makeValidName(cond);
    neural_tensor = drsa_input.(field).neural;
    observed_position = model_input.(field).observed_position;
    observed_direction = model_input.(field).observed_direction;

    model_cell = cell(1, 2);
    model_names = { ...
        drsa_stage_utils.stimulus_model_label(cond, 'observed', 'position'), ...
        drsa_stage_utils.stimulus_model_label(cond, 'observed', 'direction')};
    model_axis_labels = { ...
        drsa_stage_utils.model_time_axis_label(cond, 'observed', 'position'), ...
        drsa_stage_utils.model_time_axis_label(cond, 'observed', 'direction')};
    model_source_conditions = repmat( ...
        {model_input.(field).observed_source_condition}, 1, 2);
    model_dist = {'euclidean', 'cosine'};
    model_cell{1} = dRSA_concatenate(observed_position, [], 0, 'suppressDispText', 1);
    model_cell{2} = dRSA_concatenate(observed_direction, [], 0, 'suppressDispText', 1);

    if strcmp(cond, 'occluded_deviant')
        predicted_position = model_input.occluded_deviant.predicted_position;
        predicted_direction = model_input.occluded_deviant.predicted_direction;
        pe_position = observed_position - predicted_position;
        pe_direction = observed_direction - predicted_direction;
        model_cell{3} = dRSA_concatenate(predicted_position, [], 0, 'suppressDispText', 1);
        model_cell{4} = dRSA_concatenate(predicted_direction, [], 0, 'suppressDispText', 1);
        model_cell{5} = dRSA_concatenate(pe_position, [], 0, 'suppressDispText', 1);
        model_cell{6} = dRSA_concatenate(pe_direction, [], 0, 'suppressDispText', 1);
        model_names = { ...
            drsa_stage_utils.stimulus_model_label(cond, 'observed', 'position'), ...
            drsa_stage_utils.stimulus_model_label(cond, 'observed', 'direction'), ...
            drsa_stage_utils.stimulus_model_label(cond, 'predicted', 'position'), ...
            drsa_stage_utils.stimulus_model_label(cond, 'predicted', 'direction'), ...
            drsa_stage_utils.stimulus_model_label(cond, 'prediction_error', 'position'), ...
            drsa_stage_utils.stimulus_model_label(cond, 'prediction_error', 'direction')};
        model_axis_labels = { ...
            drsa_stage_utils.model_time_axis_label(cond, 'observed', 'position'), ...
            drsa_stage_utils.model_time_axis_label(cond, 'observed', 'direction'), ...
            drsa_stage_utils.model_time_axis_label(cond, 'predicted', 'position'), ...
            drsa_stage_utils.model_time_axis_label(cond, 'predicted', 'direction'), ...
            drsa_stage_utils.model_time_axis_label(cond, 'prediction_error', 'position'), ...
            drsa_stage_utils.model_time_axis_label(cond, 'prediction_error', 'direction')};
        model_source_conditions = { ...
            'occluded_deviant', 'occluded_deviant', ...
            model_input.occluded_deviant.predicted_source_condition, ...
            model_input.occluded_deviant.predicted_source_condition, ...
            'occluded_deviant-minus-occluded_nondeviant', ...
            'occluded_deviant-minus-occluded_nondeviant'};
        model_dist = {'euclidean', 'cosine', 'euclidean', 'cosine', 'euclidean', 'cosine'};
    end

    neural_concat = dRSA_concatenate(neural_tensor, [], 0, 'suppressDispText', 1);
    trial_len = size(neural_tensor, 3);
    total_time = size(neural_concat, 2);
    [subsamples, trigger_opt] = drsa_stage_utils.build_trial_subsamples(trial_len, total_time);

    params = drsa_stage_utils.build_drsa_params(dRSAtypeToRun, plotSampleRateHz, trial_len, pcrStrategy);
    params.modelNames = model_names;
    params.modelToTest = 1:numel(model_cell);
    params.modelDistMeasure = model_dist;
    params.neuralDistMeasure = 'correlation';
    params.modeltoRegressout = cell(1, numel(model_cell));
    for i_model = 1:numel(model_cell)
        params.modeltoRegressout{i_model} = setdiff(1:numel(model_cell), i_model);
    end
    params.nIter = size(subsamples, 3);

    autocorr_border = drsa_stage_utils.compute_autocorr_border(params, model_cell, subsamples);
    dRSA_neural_correlation = dRSA_coreFunction(neural_concat, model_cell, params, ...
        'CurrSubsamples', subsamples(:, :, 1), ...
        'Autocorrborder', autocorr_border, ...
        'suppressDispText', 1);

    drsa_output.(field).dRSA_neural_correlation = dRSA_neural_correlation;
    drsa_output.(field).model_names = model_names;
    drsa_output.(field).model_axis_labels = model_axis_labels;
    drsa_output.(field).model_source_conditions = model_source_conditions;
    drsa_output.(field).model_dist = model_dist;

    cond_root = fullfile(output_root, cond, lower(dRSAtypeToRun));
    matrices_dir = fullfile(cond_root, 'matrices');
    results_dir = fullfile(cond_root, 'results');
    if ~isfolder(matrices_dir), mkdir(matrices_dir); end
    if ~isfolder(results_dir), mkdir(results_dir); end

    fig_file = fullfile(matrices_dir, sprintf('dRSA_%s_%s_matrices.png', cond, lower(dRSAtypeToRun)));
    fig = figure('Name', sprintf('%s dRSA matrices (%s, %s)', ...
        handoff.subject_bids_id, cond, dRSAtypeToRun), ...
        'NumberTitle', 'off', 'Visible', 'off', 'Color', 'w');
    tiledlayout(1, numel(model_names), 'Padding', 'compact', 'TileSpacing', 'compact');
    sgtitle(sprintf('%s %s | %s | %s', ...
        handoff.subject_bids_id, handoff.session_bids_id, cond, dRSAtypeToRun), ...
        'Interpreter', 'none');
    for i_model = 1:numel(model_names)
        nexttile(i_model);
        imagesc(time_axis_sec, time_axis_sec, dRSA_neural_correlation(:, :, i_model));
        set(gca, 'YDir', 'normal');
        axis image;
        colorbar;
        title(model_names{i_model}, 'Interpreter', 'none');
        xlabel('neural time (s)');
        ylabel(model_axis_labels{i_model});
        hold on;
        plot(time_axis_sec, time_axis_sec, 'w-', 'LineWidth', 1);
        drsa_stage_utils.add_occlusion_boundary_lines(time_axis_sec, cond, handoff.occlusion_timing);
        hold off;
    end
    exportgraphics(fig, fig_file, 'Resolution', 300, 'BackgroundColor', 'white');
    close(fig);

    fig_file_smoothed = '';
    if doSmoothingPlots
        fig_file_smoothed = fullfile(matrices_dir, sprintf('dRSA_%s_%s_matrices_smoothed.png', cond, lower(dRSAtypeToRun)));
        fig = figure('Name', sprintf('%s dRSA matrices smoothed (%s, %s)', ...
            handoff.subject_bids_id, cond, dRSAtypeToRun), ...
            'NumberTitle', 'off', 'Visible', 'off', 'Color', 'w');
        tiledlayout(1, numel(model_names), 'Padding', 'compact', 'TileSpacing', 'compact');
        sgtitle(sprintf('%s %s | %s | %s | smoothed', ...
            handoff.subject_bids_id, handoff.session_bids_id, cond, dRSAtypeToRun), ...
            'Interpreter', 'none');
        for i_model = 1:numel(model_names)
            smoothed_matrix = drsa_stage_utils.smooth_matrix_for_plot( ...
                dRSA_neural_correlation(:, :, i_model), plotSmoothingWindow);
            nexttile(i_model);
            imagesc(time_axis_sec, time_axis_sec, smoothed_matrix);
            set(gca, 'YDir', 'normal');
            axis image;
            colorbar;
            title([model_names{i_model} ' smoothed'], 'Interpreter', 'none');
            xlabel('neural time (s)');
            ylabel(model_axis_labels{i_model});
            hold on;
            plot(time_axis_sec, time_axis_sec, 'w-', 'LineWidth', 1);
            drsa_stage_utils.add_occlusion_boundary_lines(time_axis_sec, cond, handoff.occlusion_timing);
            hold off;
        end
        exportgraphics(fig, fig_file_smoothed, 'Resolution', 300, 'BackgroundColor', 'white');
        close(fig);
    end

    results_file = fullfile(results_dir, sprintf('dRSA_%s_%s_results.mat', cond, lower(dRSAtypeToRun)));
    % Result arrays are small enough for MATLAB v7 and remain readable from
    % Python scipy for numeric group averaging.
    save(results_file, 'dRSA_neural_correlation', 'model_names', ...
        'model_axis_labels', 'model_source_conditions', 'model_dist', 'params', 'handoff', ...
        'identity_values', 'time_axis_sec', ...
        'kept_channel_labels', 'removed_channel_labels', 'trigger_opt', ...
        'fig_file', 'fig_file_smoothed', 'doSmoothingPlots', ...
        'plotSmoothingWindow', '-v7');

    fprintf('Saved real-neural dRSA outputs for %s:\n  %s\n  %s\n', ...
        cond, fig_file, results_file);
end

fprintf('A_dRSA complete. Outputs written under:\n%s\n', output_root);
