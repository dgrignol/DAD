% dRSA_simulations.m
%
% Purpose:
%   Run optional dRSA simulation-style analyses for one DAD participant using
%   the Stage-07 handoff. The script computes model-vs-model matrices and
%   neural-vs-neural autocorrelation matrices for selected MEGIN sensor groups.
%
% Usage examples:
%   drsa_handoff_json = '/Volumes/MORWUR/Projects/DAMIANO/Attention/derivatives/reports/sub-04/ses-01/07_matlab_drsa_handoff.json';
%   conditions_to_run = {'always_visible', 'occluded_deviant'};
%   sensor_groups_to_run = {'wholeBrain', 'occipital'};
%   dRSAtypeToRun = 'corr';
%   model_path_source = 'observed';
%   run('/Users/damiano/Documents/UniTn/Dynamo/Attention/DAD/meg/code/analysis/dRSA_simulations.m');
%
% Inputs:
%   - drsa_handoff_json generated by 07_run_matlab_drsa.py.
%   - Stage-06 neural MAT/JSON outputs.
%   - Observed trajectory MAT referenced by the handoff. Its matched
%     occluded_nondeviant trials supply the expected continuation.
%
% Outputs:
%   <drsa_dir>/simulations/model_vs_model/<condition>/<drsa_type>/{matrices,results}
%     for always_visible and occluded_nondeviant observed-model outputs.
%   <drsa_dir>/simulations/model_vs_model/occluded_deviant/<source>/<drsa_type>/{matrices,results}
%     for observed actual-deviant and expected/predicted occluded-deviant outputs.
%   <drsa_dir>/simulations/neural_vs_neural/<condition>/corr/{matrices,results}
%   Add doSmoothingPlots=true to also write *_smoothed.png display figures.
%   Occluded-condition matrix PNGs include dashed horizontal lines marking
%   first complete occlusion and first reappearance from the handoff timing.
%
% Data flow:
%   handoff JSON -> sorted trajectory tensors -> model-vs-model dRSA;
%   handoff JSON -> neural tensor -> sensor-group slices -> neural-vs-neural dRSA.

%% Reset workspace while preserving runtime overrides
clearvars -except drsa_handoff_json conditions_to_run sensor_groups_to_run dRSAtypeToRun plotSampleRateHz pcrStrategy doSmoothNeural smoothWindowSamples doSmoothingPlots plotSmoothingWindow model_path_source output_root_override

%% Runtime defaults and handoff
if ~exist('drsa_handoff_json', 'var') || isempty(drsa_handoff_json)
    error('Set drsa_handoff_json before running dRSA_simulations.m.');
end
if ~exist('conditions_to_run', 'var') || isempty(conditions_to_run)
    conditions_to_run = {'always_visible', 'occluded_nondeviant', 'occluded_deviant'};
end
if ischar(conditions_to_run) || isstring(conditions_to_run)
    conditions_to_run = cellstr(conditions_to_run);
end
if ~exist('sensor_groups_to_run', 'var') || isempty(sensor_groups_to_run)
    sensor_groups_to_run = {'wholeBrain', 'occipital', 'parietal', 'frontal', 'temporal'};
end
if ischar(sensor_groups_to_run) || isstring(sensor_groups_to_run)
    sensor_groups_to_run = cellstr(sensor_groups_to_run);
end
if ~exist('dRSAtypeToRun', 'var') || isempty(dRSAtypeToRun), dRSAtypeToRun = 'corr'; end
if ~exist('pcrStrategy', 'var') || isempty(pcrStrategy), pcrStrategy = 'baseline_pcr_border'; end
if ~exist('doSmoothNeural', 'var') || isempty(doSmoothNeural), doSmoothNeural = true; end
if ~exist('smoothWindowSamples', 'var') || isempty(smoothWindowSamples), smoothWindowSamples = 15; end
if ~exist('doSmoothingPlots', 'var') || isempty(doSmoothingPlots), doSmoothingPlots = false; end
if ~exist('plotSmoothingWindow', 'var') || isempty(plotSmoothingWindow), plotSmoothingWindow = 9; end
if ~exist('model_path_source', 'var') || isempty(model_path_source), model_path_source = 'observed'; end

handoff = drsa_stage_utils.load_handoff(drsa_handoff_json);
drsa_stage_utils.add_helper_paths(handoff);
if ~exist('plotSampleRateHz', 'var') || isempty(plotSampleRateHz)
    plotSampleRateHz = double(handoff.sampling_rate_hz);
end
if exist('output_root_override', 'var') && ~isempty(output_root_override)
    base_out_dir = char(output_root_override);
else
    base_out_dir = handoff.drsa_dir;
end

identity_values = drsa_stage_utils.vectorize_numeric(handoff.identity_values);
time_axis_sec = drsa_stage_utils.vectorize_numeric(handoff.time_axis_sec);
Obs = drsa_stage_utils.load_models(handoff);
sensor_group_lists = drsa_stage_utils.get_megin_sensor_groups();

fprintf('Running dRSA simulations for %s %s under %s\n', ...
    handoff.subject_bids_id, handoff.session_bids_id, base_out_dir);

%% Condition loop
for i_cond = 1:numel(conditions_to_run)
    condition_str = lower(strtrim(char(conditions_to_run{i_cond})));
    [neural, channel_labels, ~] = drsa_stage_utils.load_neural_condition(handoff, condition_str);
    [neural, channel_labels, removed_labels] = drsa_stage_utils.remove_all_nan_channels(neural, channel_labels);
    if doSmoothNeural
        neural = smoothdata(neural, 3, 'gaussian', smoothWindowSamples);
    end

    n_time = size(neural, 3);
    [model_trials, model_source_used, model_center_shift, model_source_condition] = ...
        drsa_stage_utils.model_trials_for_condition(condition_str, model_path_source, Obs);
    model_trials_sorted = drsa_stage_utils.sort_and_validate_sequences(model_trials, identity_values);
    [model_position, model_direction] = drsa_stage_utils.build_position_direction( ...
        model_trials_sorted, identity_values, n_time, model_center_shift);

    model_pos_concat = dRSA_concatenate(model_position, [], 0, 'suppressDispText', 1);
    model_dir_concat = dRSA_concatenate(model_direction, [], 0, 'suppressDispText', 1);
    [subsamples, trigger_opt] = drsa_stage_utils.build_trial_subsamples(n_time, size(model_pos_concat, 2));
    position_model_label = drsa_stage_utils.stimulus_model_label( ...
        condition_str, model_source_used, 'position');
    direction_model_label = drsa_stage_utils.stimulus_model_label( ...
        condition_str, model_source_used, 'direction');
    position_axis_label = drsa_stage_utils.model_time_axis_label( ...
        condition_str, model_source_used, 'position');
    direction_axis_label = drsa_stage_utils.model_time_axis_label( ...
        condition_str, model_source_used, 'direction');

    %% Model-vs-model simulations
    if strcmp(condition_str, 'occluded_deviant')
        model_out_root = fullfile(base_out_dir, 'simulations', 'model_vs_model', ...
            condition_str, lower(model_source_used), lower(dRSAtypeToRun));
        model_base_tag = sprintf('dRSA_simulations_%s_%s_%s', ...
            condition_str, lower(model_source_used), lower(dRSAtypeToRun));
    else
        model_out_root = fullfile(base_out_dir, 'simulations', 'model_vs_model', ...
            condition_str, lower(dRSAtypeToRun));
        model_base_tag = sprintf('dRSA_simulations_%s_%s', ...
            condition_str, lower(dRSAtypeToRun));
    end
    model_matrices_dir = fullfile(model_out_root, 'matrices');
    model_results_dir = fullfile(model_out_root, 'results');
    if ~isfolder(model_matrices_dir), mkdir(model_matrices_dir); end
    if ~isfolder(model_results_dir), mkdir(model_results_dir); end

    model_params_self = drsa_stage_utils.build_drsa_params(lower(dRSAtypeToRun), plotSampleRateHz, n_time, pcrStrategy);
    model_params_self.modelNames = {position_model_label};
    model_params_self.modelToTest = 1;
    model_params_self.modeltoRegressout = {[]};
    if strcmpi(model_params_self.dRSAtype, 'corr')
        model_params_self.modelDistMeasure = 'euclidean';
    else
        model_params_self.modelDistMeasure = {'euclidean'};
    end
    model_params_self.neuralDistMeasure = 'euclidean';
    model_border_self = drsa_stage_utils.compute_autocorr_border(model_params_self, {model_pos_concat}, subsamples);
    dRSA_model_pos_pos = dRSA_coreFunction(model_pos_concat, {model_pos_concat}, model_params_self, ...
        'CurrSubsamples', subsamples(:, :, 1), 'Autocorrborder', model_border_self, 'suppressDispText', 1);

    model_params_cross = drsa_stage_utils.build_drsa_params(lower(dRSAtypeToRun), plotSampleRateHz, n_time, pcrStrategy);
    model_params_cross.modelNames = {direction_model_label};
    model_params_cross.modelToTest = 1;
    model_params_cross.modeltoRegressout = {[]};
    model_params_cross.modelDistMeasure = {'cosine'};
    model_params_cross.neuralDistMeasure = 'euclidean';
    model_border_cross = drsa_stage_utils.compute_autocorr_border(model_params_cross, {model_dir_concat}, subsamples);
    dRSA_model_pos_dir = dRSA_coreFunction(model_pos_concat, {model_dir_concat}, model_params_cross, ...
        'CurrSubsamples', subsamples(:, :, 1), 'Autocorrborder', model_border_cross, 'suppressDispText', 1);

    model_fig_pos_pos = fullfile(model_matrices_dir, sprintf('%s_position_with_position.png', model_base_tag));
    model_fig_pos_dir = fullfile(model_matrices_dir, sprintf('%s_position_with_direction.png', model_base_tag));
    drsa_stage_utils.export_matrix_figure(dRSA_model_pos_pos(:, :, 1), plotSampleRateHz, ...
        sprintf('%s | Model simulation: position with position | %s | %s', ...
            handoff.subject_bids_id, condition_str, position_model_label), ...
        model_fig_pos_pos, condition_str, handoff.occlusion_timing, position_axis_label);
    drsa_stage_utils.export_matrix_figure(dRSA_model_pos_dir(:, :, 1), plotSampleRateHz, ...
        sprintf('%s | Model simulation: position with direction | %s | %s', ...
            handoff.subject_bids_id, condition_str, direction_model_label), ...
        model_fig_pos_dir, condition_str, handoff.occlusion_timing, direction_axis_label);

    model_fig_pos_pos_smoothed = '';
    model_fig_pos_dir_smoothed = '';
    if doSmoothingPlots
        model_fig_pos_pos_smoothed = fullfile(model_matrices_dir, sprintf('%s_position_with_position_smoothed.png', model_base_tag));
        model_fig_pos_dir_smoothed = fullfile(model_matrices_dir, sprintf('%s_position_with_direction_smoothed.png', model_base_tag));
        drsa_stage_utils.export_matrix_figure( ...
            drsa_stage_utils.smooth_matrix_for_plot(dRSA_model_pos_pos(:, :, 1), plotSmoothingWindow), ...
            plotSampleRateHz, ...
            sprintf('%s | Model simulation smoothed: position with position | %s | %s', ...
                handoff.subject_bids_id, condition_str, position_model_label), ...
            model_fig_pos_pos_smoothed, condition_str, handoff.occlusion_timing, position_axis_label);
        drsa_stage_utils.export_matrix_figure( ...
            drsa_stage_utils.smooth_matrix_for_plot(dRSA_model_pos_dir(:, :, 1), plotSmoothingWindow), ...
            plotSampleRateHz, ...
            sprintf('%s | Model simulation smoothed: position with direction | %s | %s', ...
                handoff.subject_bids_id, condition_str, direction_model_label), ...
            model_fig_pos_dir_smoothed, condition_str, handoff.occlusion_timing, direction_axis_label);
    end

    model_res_file = fullfile(model_results_dir, sprintf('%s_model_vs_model.mat', model_base_tag));
    % Result arrays are small enough for MATLAB v7 and remain readable from
    % Python scipy for numeric group averaging.
    save(model_res_file, 'dRSA_model_pos_pos', 'dRSA_model_pos_dir', ...
        'model_params_self', 'model_params_cross', 'condition_str', ...
        'model_path_source', 'model_source_used', 'handoff', ...
        'model_source_condition', ...
        'position_model_label', 'direction_model_label', ...
        'position_axis_label', 'direction_axis_label', ...
        'time_axis_sec', 'model_fig_pos_pos', 'model_fig_pos_dir', ...
        'model_fig_pos_pos_smoothed', 'model_fig_pos_dir_smoothed', ...
        'doSmoothingPlots', 'plotSmoothingWindow', 'trigger_opt', '-v7');

    %% Neural-vs-neural autocorrelation per sensor group
    neural_out_root = fullfile(base_out_dir, 'simulations', 'neural_vs_neural', condition_str, 'corr');
    neural_matrices_dir = fullfile(neural_out_root, 'matrices');
    neural_results_dir = fullfile(neural_out_root, 'results');
    if ~isfolder(neural_matrices_dir), mkdir(neural_matrices_dir); end
    if ~isfolder(neural_results_dir), mkdir(neural_results_dir); end

    for i_group = 1:numel(sensor_groups_to_run)
        [sensor_group_key, sensor_group_tag] = drsa_stage_utils.normalize_sensor_group(sensor_groups_to_run{i_group});
        target_labels = string(sensor_group_lists.(sensor_group_key)(:));
        selected_mask = ismember(channel_labels, target_labels);
        selected_labels = channel_labels(selected_mask);
        if ~any(selected_mask)
            error('No channels selected for group %s in condition %s.', sensor_group_tag, condition_str);
        end

        neural_group = neural(:, selected_mask, :);
        neural_concat = dRSA_concatenate(neural_group, [], 0, 'suppressDispText', 1);
        neural_params = drsa_stage_utils.build_drsa_params('corr', plotSampleRateHz, n_time, pcrStrategy);
        neural_params.modelNames = {sprintf('neural %s', sensor_group_tag)};
        neural_params.modelToTest = 1;
        neural_params.modeltoRegressout = {[]};
        neural_params.modelDistMeasure = 'correlation';
        neural_params.neuralDistMeasure = 'correlation';
        dRSA_neural_self = dRSA_coreFunction(neural_concat, {neural_concat}, neural_params, ...
            'CurrSubsamples', subsamples(:, :, 1), 'Autocorrborder', [], 'suppressDispText', 1);

        neural_base_tag = sprintf('dRSA_simulations_%s_corr_neural_with_neural_%s', ...
            condition_str, sensor_group_tag);
        neural_axis_label = drsa_stage_utils.model_time_axis_label( ...
            condition_str, 'neural', 'neural signal');
        neural_fig_file = fullfile(neural_matrices_dir, sprintf('%s.png', neural_base_tag));
        drsa_stage_utils.export_matrix_figure(dRSA_neural_self(:, :, 1), plotSampleRateHz, ...
            sprintf('%s | Neural autocorr: %s (%s)', ...
                handoff.subject_bids_id, sensor_group_tag, condition_str), ...
            neural_fig_file, condition_str, handoff.occlusion_timing, neural_axis_label);

        neural_fig_file_smoothed = '';
        if doSmoothingPlots
            neural_fig_file_smoothed = fullfile(neural_matrices_dir, sprintf('%s_smoothed.png', neural_base_tag));
            drsa_stage_utils.export_matrix_figure( ...
                drsa_stage_utils.smooth_matrix_for_plot(dRSA_neural_self(:, :, 1), plotSmoothingWindow), ...
                plotSampleRateHz, ...
                sprintf('%s | Neural autocorr smoothed: %s (%s)', ...
                    handoff.subject_bids_id, sensor_group_tag, condition_str), ...
                neural_fig_file_smoothed, condition_str, handoff.occlusion_timing, neural_axis_label);
        end

        neural_res_file = fullfile(neural_results_dir, sprintf('%s.mat', neural_base_tag));
        save(neural_res_file, 'dRSA_neural_self', 'neural_params', ...
            'condition_str', 'sensor_group_key', 'sensor_group_tag', ...
            'selected_labels', 'removed_labels', 'neural_fig_file', ...
            'neural_fig_file_smoothed', 'neural_axis_label', 'time_axis_sec', ...
            'doSmoothingPlots', 'plotSmoothingWindow', 'trigger_opt', ...
            'handoff', '-v7');

        fprintf('Saved simulation neural autocorrelation (%s, %s):\n  %s\n  %s\n', ...
            condition_str, sensor_group_tag, neural_fig_file, neural_res_file);
    end

    fprintf('Completed simulations for %s using %s model paths.\n', ...
        condition_str, model_source_used);
end

fprintf('dRSA_simulations complete.\n');
