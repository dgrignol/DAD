classdef drsa_stage_utils
    % drsa_stage_utils
    %
    % Purpose:
    %   Shared MATLAB utilities for the DAD Stage-07 dRSA analysis scripts.
    %   These methods consume the Python-generated 07_matlab_drsa_handoff.json
    %   and keep path resolution, Stage-06 sidecar validation, model sorting,
    %   sensor-group selection, and headless figure export consistent across
    %   A_dRSA.m, A_dRSA_alt.m, and dRSA_simulations.m.
    %   Occluded-condition figures can add dashed horizontal event-boundary
    %   overlays using the Python-generated handoff occlusion timing.
    %
    % Usage examples:
    %   handoff = drsa_stage_utils.load_handoff('/path/to/07_matlab_drsa_handoff.json');
    %   drsa_stage_utils.add_helper_paths(handoff);
    %   [neural, labels, sidecar] = drsa_stage_utils.load_neural_condition(handoff, 'always_visible');
    %   Obs = drsa_stage_utils.load_models(handoff);
    %
    % Data flow:
    %   handoff JSON -> Stage-06 MAT/JSON files + trajectory MAT files ->
    %   validated neural/model tensors -> dRSA scripts.
    %
    % Assumptions:
    %   - The handoff was generated by 07_run_matlab_drsa.py from a resolved
    %     pipeline configuration.
    %   - Stage-06 sidecars are authoritative for identity values, time axis,
    %     model paths, condition labels, and channel labels.
    %   - Identity values must map one-to-one to model sequence values.

    methods(Static)
        function handoff = load_handoff(path_value)
            % Read and minimally validate one Python-generated handoff JSON.
            if nargin < 1 || isempty(path_value)
                error('A drsa_handoff_json path is required.');
            end
            handoff_path = char(path_value);
            if ~isfile(handoff_path)
                error('Handoff JSON not found: %s', handoff_path);
            end
            handoff = jsondecode(fileread(handoff_path));
            required = {'version', 'subject_bids_id', 'session_bids_id', ...
                'drsa_dir', 'drsa_functions_dir', 'trajectory_models', ...
                'condition_outputs', 'identity_values', 'time_axis_sec', ...
                'sampling_rate_hz'};
            for i_req = 1:numel(required)
                if ~isfield(handoff, required{i_req})
                    error('Handoff JSON is missing required field: %s', required{i_req});
                end
            end
            if ~isfield(handoff, 'occlusion_timing')
                % Older Stage-07 handoffs predate plot-boundary overlays.
                % Supplying an empty struct keeps direct MATLAB reruns valid.
                handoff.occlusion_timing = struct();
            end
        end

        function add_helper_paths(handoff)
            % Put the dRSA helper functions and current analysis folder on path.
            if ~isfolder(handoff.drsa_functions_dir)
                error('Missing dRSA helper directory: %s', handoff.drsa_functions_dir);
            end
            addpath(handoff.drsa_functions_dir);
            addpath(fileparts(mfilename('fullpath')));
            required_funcs = {'dRSA_concatenate', 'dRSA_coreFunction', ...
                'dRSA_triggered_subsampling'};
            for i_func = 1:numel(required_funcs)
                if exist(required_funcs{i_func}, 'file') ~= 2
                    error('Missing required dRSA helper function: %s', required_funcs{i_func});
                end
            end
        end

        function condition_info = get_condition(handoff, condition_name)
            % Return the handoff entry for one named condition.
            condition_name = char(condition_name);
            conditions = handoff.condition_outputs;
            for i_cond = 1:numel(conditions)
                if strcmp(char(conditions(i_cond).name), condition_name)
                    condition_info = conditions(i_cond);
                    return;
                end
            end
            error('Condition %s is absent from the handoff.', condition_name);
        end

        function [neural, channel_labels, sidecar] = load_neural_condition(handoff, condition_name)
            % Load and validate one Stage-06 neural tensor and JSON sidecar.
            condition_info = drsa_stage_utils.get_condition(handoff, condition_name);
            if ~isfile(condition_info.neural_mat)
                error('Neural MAT file not found: %s', condition_info.neural_mat);
            end
            if ~isfile(condition_info.sidecar_json)
                error('Neural sidecar JSON not found: %s', condition_info.sidecar_json);
            end
            sidecar = jsondecode(fileread(condition_info.sidecar_json));
            N = load(condition_info.neural_mat, 'neural', 'channel_labels', 'time_axis_sec', 'identity_values');
            if ~isfield(N, 'neural') || ~isnumeric(N.neural) || ndims(N.neural) ~= 3
                error('File %s must contain numeric neural [identity x channels x time].', condition_info.neural_mat);
            end
            if ~isfield(N, 'channel_labels')
                error('File %s is missing channel_labels.', condition_info.neural_mat);
            end
            neural = N.neural;
            channel_labels = string(N.channel_labels(:));
            identity_values = drsa_stage_utils.vectorize_numeric(handoff.identity_values);
            time_axis = drsa_stage_utils.vectorize_numeric(handoff.time_axis_sec);
            if size(neural, 1) ~= numel(identity_values)
                error('Identity axis mismatch for %s: neural=%d handoff=%d.', ...
                    condition_name, size(neural, 1), numel(identity_values));
            end
            if size(neural, 3) ~= numel(time_axis)
                error('Time axis mismatch for %s: neural=%d handoff=%d.', ...
                    condition_name, size(neural, 3), numel(time_axis));
            end
            if numel(channel_labels) ~= size(neural, 2)
                error('Channel label count mismatch for %s: labels=%d neural=%d.', ...
                    condition_name, numel(channel_labels), size(neural, 2));
            end
            if isfield(sidecar, 'condition_name') && ~strcmp(char(sidecar.condition_name), char(condition_name))
                error('Sidecar condition mismatch in %s.', condition_info.sidecar_json);
            end
        end

        function Obs = load_models(handoff)
            % Load the observed trajectory MAT and validate shared path identities.
            observed_path = handoff.trajectory_models.observed;
            if ~isfile(observed_path)
                error('Observed trajectory model not found: %s', observed_path);
            end
            Obs = load(observed_path, 'xySeqs', 'Cfg');
            if ~isfield(Obs, 'xySeqs') || isempty(Obs.xySeqs)
                error('Observed model must contain non-empty xySeqs: %s', observed_path);
            end
            drsa_stage_utils.validate_expected_path_correspondence(Obs.xySeqs);
        end

        function [trials, model_source_used, center_shift, source_condition] = ...
                model_trials_for_condition(condition_name, model_source, Obs)
            % Select observed or expected trials from the shared observed MAT.
            condition_name = char(condition_name);
            model_source = strtrim(char(model_source));
            if strcmpi(model_source, 'predicted') && strcmpi(condition_name, 'occluded_deviant')
                obs_trials = Obs.xySeqs(:);
                obs_labels = lower(string({obs_trials.condition_label}));
                source_condition = 'occluded_nondeviant';
                trials = obs_trials(obs_labels == string(source_condition));
                model_source_used = 'predicted';
            else
                obs_trials = Obs.xySeqs(:);
                obs_labels = lower(string({obs_trials.condition_label}));
                trials = obs_trials(obs_labels == string(condition_name));
                model_source_used = 'observed';
                source_condition = condition_name;
            end
            if isempty(trials)
                error('No model trials found for condition=%s source=%s source_condition=%s.', ...
                    condition_name, model_source_used, source_condition);
            end
            rect_size = double(Obs.Cfg.rectSize(:));
            if numel(rect_size) ~= 2
                error('Cfg.rectSize must contain [width height].');
            end
            center_shift = reshape(rect_size ./ 2, [1, 2, 1]);
        end

        function validate_expected_path_correspondence(xy_seqs)
            % Validate the shared-path invariant used by the expected model.
            trials = xy_seqs(:);
            if ~isfield(trials, 'condition_label') || ~isfield(trials, 'sequence') || ...
                    ~isfield(trials, 'xy')
                error('xySeqs must contain condition_label, sequence, and xy fields.');
            end
            labels = lower(string({trials.condition_label}));
            visible = trials(labels == "always_visible");
            nondeviant = trials(labels == "occluded_nondeviant");
            deviant = trials(labels == "occluded_deviant");
            if isempty(visible) || isempty(nondeviant) || isempty(deviant)
                error(['Expected always_visible, occluded_nondeviant, and ' ...
                    'occluded_deviant trials in the observed trajectory MAT.']);
            end

            [visible, visible_sequences] = drsa_stage_utils.sort_trials_by_sequence(visible);
            [nondeviant, nondeviant_sequences] = drsa_stage_utils.sort_trials_by_sequence(nondeviant);
            [deviant, deviant_sequences] = drsa_stage_utils.sort_trials_by_sequence(deviant);
            if ~isequal(visible_sequences, nondeviant_sequences) || ...
                    ~isequal(visible_sequences, deviant_sequences)
                error('Condition trajectory sequence identities do not match.');
            end

            for i_trial = 1:numel(visible)
                visible_xy = double(visible(i_trial).xy);
                nondeviant_xy = double(nondeviant(i_trial).xy);
                deviant_xy = double(deviant(i_trial).xy);
                if ~isequal(size(visible_xy), size(nondeviant_xy), size(deviant_xy))
                    error('Trajectory shape mismatch for sequence %d.', visible_sequences(i_trial));
                end
                if ~isequaln(visible_xy, nondeviant_xy)
                    error(['always_visible and occluded_nondeviant paths differ ' ...
                        'for sequence %d.'], visible_sequences(i_trial));
                end
                if ~isfield(deviant(i_trial), 'deviance_frame')
                    error('occluded_deviant sequence %d lacks deviance_frame.', visible_sequences(i_trial));
                end
                deviance_frame = round(double(deviant(i_trial).deviance_frame));
                if ~isscalar(deviance_frame) || ~isfinite(deviance_frame) || ...
                        deviance_frame < 1 || deviance_frame > size(deviant_xy, 1)
                    error('Invalid deviance_frame for sequence %d.', visible_sequences(i_trial));
                end
                if ~isequaln(deviant_xy(1:deviance_frame, :), ...
                        nondeviant_xy(1:deviance_frame, :))
                    error(['occluded_deviant and occluded_nondeviant prefixes differ ' ...
                        'through deviance_frame for sequence %d.'], visible_sequences(i_trial));
                end
            end
        end

        function [sorted_trials, sequence_values] = sort_trials_by_sequence(trials)
            % Sort a condition subset by numeric sequence identity.
            sequence_values = round(double([trials.sequence]));
            [sequence_values, order] = sort(sequence_values);
            sorted_trials = trials(order);
            sequence_values = sequence_values(:)';
        end

        function sorted_trials = sort_and_validate_sequences(trials, identity_values)
            % Sort trajectory trials by sequence and require one per identity.
            if ~isfield(trials, 'sequence') || ~isfield(trials, 'xy')
                error('Model trials must contain sequence and xy fields.');
            end
            expected = drsa_stage_utils.vectorize_numeric(identity_values);
            seq_values = round(double([trials.sequence]));
            [seq_sorted, order] = sort(seq_values);
            if numel(seq_sorted) ~= numel(expected) || ~isequal(seq_sorted(:)', expected(:)')
                error('Model sequence values must match identity axis. Expected %s, found %s.', ...
                    mat2str(expected(:)'), mat2str(seq_sorted(:)'));
            end
            sorted_trials = trials(order);
        end

        function [position_tensor, direction_tensor] = build_position_direction( ...
                sorted_trials, identity_values, n_time, center_shift)
            % Build position and direction tensors from sorted trajectory trials.
            n_identity = numel(drsa_stage_utils.vectorize_numeric(identity_values));
            position_tensor = zeros(n_identity, 2, n_time);
            for i_id = 1:n_identity
                xy = double(sorted_trials(i_id).xy);
                if size(xy, 2) ~= 2
                    error('Expected one-dot xy with 2 columns for identity index %d.', i_id);
                end
                if size(xy, 1) ~= n_time
                    error('Model/neural time mismatch for identity index %d: model=%d neural=%d.', ...
                        i_id, size(xy, 1), n_time);
                end
                position_tensor(i_id, 1, :) = reshape(xy(:, 1), 1, 1, []);
                position_tensor(i_id, 2, :) = reshape(xy(:, 2), 1, 1, []);
            end
            position_tensor = bsxfun(@minus, position_tensor, center_shift);
            direction_tensor = drsa_stage_utils.positions_to_direction(position_tensor);
        end

        function direction_tensor = positions_to_direction(position_tensor)
            % Convert position [identity x 2 x time] into cos/sin direction.
            dx = diff(position_tensor(:, 1, :), 1, 3);
            dy = diff(position_tensor(:, 2, :), 1, 3);
            dx = cat(3, dx(:, :, 1), dx);
            dy = cat(3, dy(:, :, 1), dy);
            direction_tensor = cat(2, cos(atan2(dy, dx)), sin(atan2(dy, dx)));
        end

        function [subsamples, opt] = build_trial_subsamples(trial_len, total_time)
            % Build triggered subsamples with one full window per identity epoch.
            trial_starts = 1:trial_len:total_time;
            if isempty(trial_starts) || trial_starts(end) + trial_len - 1 > total_time
                error('Trial subsampling mismatch: trial_len=%d total_time=%d.', ...
                    trial_len, total_time);
            end
            mask_subsampling = true(1, total_time);
            mask_trigger = false(1, total_time);
            mask_trigger(trial_starts) = true;
            opt = struct();
            opt.PreTrigger = 0;
            opt.PostTrigger = trial_len - 1;
            opt.spacing = 0;
            opt.nSubSamples = numel(trial_starts);
            opt.nIter = 1;
            opt.checkRepetition = 0;
            subsamples = dRSA_triggered_subsampling(mask_subsampling, mask_trigger, opt, 'suppressDispText', 1);
        end

        function params = build_drsa_params(drsa_type, fs_hz, trial_len, pcr_strategy)
            % Build shared dRSA parameter defaults.
            params = struct();
            params.dRSAtype = char(drsa_type);
            params.nIter = 1;
            params.fs = double(fs_hz);
            params.AverageTime = floor((trial_len - 1) / 2) / params.fs;
            params.Var = 0.1;
            params.PCR = struct();
            params.PCR.RegressStrategy = char(pcr_strategy);
            params.PCR.RegressAutocor = 1;
            params.PCR.RessModel = 1;
            params.PCR.AdditionalPCA = 1;
        end

        function border = compute_autocorr_border(params, models_cell, subsamples)
            % Compute PCR autocorrelation borders only when the analysis needs them.
            border = [];
            if strcmpi(params.dRSAtype, 'PCR')
                if exist('dRSA_border', 'file') ~= 2
                    error('PCR mode requires dRSA_border.m on the MATLAB path.');
                end
                border = dRSA_border(models_cell, subsamples, params, ...
                    'suppressDispText', 1, 'plotAutocorr', 'off');
            end
        end

        function [neural, channel_labels, removed_labels] = remove_all_nan_channels(neural, channel_labels)
            % Remove channels exported as all-NaN over identities x time.
            channel_labels = string(channel_labels(:));
            if numel(channel_labels) ~= size(neural, 2)
                error('channel_labels count does not match neural channel axis.');
            end
            nan_mask = squeeze(all(all(isnan(neural), 3), 1));
            removed_labels = cellstr(channel_labels(nan_mask));
            neural = neural(:, ~nan_mask, :);
            channel_labels = channel_labels(~nan_mask);
            if size(neural, 2) == 0
                error('No channels remain after removing all-NaN channels.');
            end
        end

