        function [key, tag] = normalize_sensor_group(value)
            % Normalize one sensor-group name to a field key and output tag.
            raw = lower(strtrim(char(value)));
            if strcmp(raw, 'wholebrain') || strcmp(raw, 'whole_brain')
                key = 'wholebrain';
            elseif strcmp(raw, 'occipital')
                key = 'occipital';
            elseif strcmp(raw, 'parietal') || strcmp(raw, 'pariatel')
                key = 'parietal';
            elseif strcmp(raw, 'frontal')
                key = 'frontal';
            elseif strcmp(raw, 'temporal')
                key = 'temporal';
            else
                error('Unknown sensor group: %s', value);
            end
            tag = key;
        end

        function smoothed_matrix = smooth_matrix_for_plot(matrix_2d, window_samples)
            % Smooth one dRSA matrix for display-only PNG export.
            % Undefined cells mark analysis support, so restore that mask after
            % smoothing to avoid displaying or summarizing impossible regions.
            if nargin < 2 || isempty(window_samples)
                window_samples = 9;
            end
            window_samples = max(1, round(double(window_samples)));
            smoothed_matrix = double(matrix_2d);
            finite_mask = isfinite(smoothed_matrix);
            if window_samples <= 1
                return;
            end
            smoothed_matrix = smoothdata(smoothed_matrix, 1, 'gaussian', window_samples);
            smoothed_matrix = smoothdata(smoothed_matrix, 2, 'gaussian', window_samples);
            smoothed_matrix(~finite_mask) = NaN;
        end

        function label = stimulus_model_label(condition_name, model_source, feature_name)
            % Build the explicit stimulus/comparison model label used in plots.
            if nargin < 3 || isempty(feature_name)
                feature_name = 'position';
            end
            condition_name = lower(strtrim(char(condition_name)));
            model_source = lower(strtrim(char(model_source)));
            feature_name = lower(strtrim(char(feature_name)));
            feature_name = strrep(feature_name, '_', ' ');

            if strcmp(model_source, 'predicted')
                prefix = 'expected/predicted';
            elseif strcmp(model_source, 'prediction_error') || strcmp(model_source, 'pe')
                prefix = 'prediction error';
            elseif strcmp(model_source, 'pe_prior_unconstrained_50')
                prefix = '50/50 unconstrained-prior PE';
            elseif strcmp(model_source, 'pe_prior_constrained_50')
                prefix = '50/50 constrained-prior PE';
            elseif strcmp(model_source, 'pe_precision_weighted')
                prefix = 'precision-weighted PE';
            elseif strcmp(model_source, 'pe_kalman_innovation')
                prefix = 'Kalman innovation PE';
            elseif strcmp(model_source, 'pe_latent_curvature')
                label = 'latent curvature PE';
                return;
            elseif strcmp(model_source, 'pe_belief_update')
                label = 'belief-update PE';
                return;
            elseif strcmp(model_source, 'neural')
                label = 'neural signal';
                return;
            elseif strcmp(condition_name, 'always_visible')
                prefix = 'actual visible';
            elseif strcmp(condition_name, 'occluded_nondeviant')
                prefix = 'actual nondeviant';
            elseif strcmp(condition_name, 'occluded_deviant')
                prefix = 'actual deviant';
            else
                prefix = 'actual/observed';
            end
            label = sprintf('%s %s', prefix, feature_name);
        end

        function label = model_time_axis_label(condition_name, model_source, feature_name)
            % Build the model-time axis label with the represented model attached.
            stimulus_label = drsa_stage_utils.stimulus_model_label( ...
                condition_name, model_source, feature_name);
            if contains(stimulus_label, 'neural signal')
                prefix = 'comparison time';
            else
                prefix = 'model time';
            end
            label = sprintf('%s (s) - %s', prefix, stimulus_label);
        end

        function add_occlusion_boundary_lines(time_axis_sec, condition_name, occlusion_timing)
            % Draw horizontal dashed occlusion boundaries for occluded conditions.
            if nargin < 3 || isempty(occlusion_timing)
                return;
            end
            if ~contains(lower(char(condition_name)), 'occluded')
                return;
            end
            if ~isfield(occlusion_timing, 'first_complete_occlusion_sec') || ...
                    ~isfield(occlusion_timing, 'reappearance_sec')
                return;
            end
            x_limits = [time_axis_sec(1), time_axis_sec(end)];
            line_times = [
                double(occlusion_timing.first_complete_occlusion_sec), ...
                double(occlusion_timing.reappearance_sec)
            ];
            for i_line = 1:numel(line_times)
                if line_times(i_line) >= x_limits(1) && line_times(i_line) <= x_limits(2)
                    plot(x_limits, [line_times(i_line), line_times(i_line)], ...
                        'w--', 'LineWidth', 1.3);
                end
            end
        end

        function export_matrix_figure(matrix_2d, fs_hz, title_text, out_file, varargin)
            % Export one dRSA matrix figure with headless-safe settings.
            condition_name = '';
            occlusion_timing = struct();
            model_axis_label = 'model time (s)';
            if numel(varargin) >= 1
                condition_name = varargin{1};
            end
            if numel(varargin) >= 2
                occlusion_timing = varargin{2};
            end
            if numel(varargin) >= 3 && ~isempty(varargin{3})
                model_axis_label = char(varargin{3});
            end
            t = (0:size(matrix_2d, 1)-1) ./ double(fs_hz);
            fig = figure('Visible', 'off', 'Color', 'w', ...
                'Name', char(title_text), 'NumberTitle', 'off');
            imagesc(t, t, matrix_2d);
            set(gca, 'YDir', 'normal');
            axis image;
            colorbar;
            xlabel('neural time (s)');
            ylabel(model_axis_label);
            title(char(title_text), 'Interpreter', 'none');
            hold on;
            plot(t, t, 'w-', 'LineWidth', 1);
            drsa_stage_utils.add_occlusion_boundary_lines(t, condition_name, occlusion_timing);
            hold off;
            exportgraphics(fig, out_file, 'Resolution', 300, 'BackgroundColor', 'white');
            close(fig);
        end

        function values = vectorize_numeric(values_in)
            % Convert JSON-decoded numeric arrays to a row double vector.
            values = double(values_in(:))';
        end
